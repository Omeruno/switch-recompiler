#!/usr/bin/env python3
"""Generate native RGBA icons from the pinned 32x32 Tango PNGs (stdlib only)."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://raw.githubusercontent.com/stephenc/tango-icon-theme/41b8f6abd7ebb9d5c35e563c8cd8c410c88f114a/'
SOURCES = [('folder', '32x32/places/folder.png'), ('computer', '32x32/devices/computer.png'),
           ('programs', '32x32/apps/system-file-manager.png')]


def decode(data):
    assert data[:8] == b'\x89PNG\r\n\x1a\n'
    offset, compressed = 8, bytearray()
    while offset < len(data):
        size, = struct.unpack_from('>I', data, offset)
        kind, payload = data[offset+4:offset+8], data[offset+8:offset+8+size]
        crc, = struct.unpack_from('>I', data, offset+8+size)
        assert zlib.crc32(kind + payload) & 0xffffffff == crc
        if kind == b'IHDR':
            assert struct.unpack('>IIBBBBB', payload) == (32, 32, 8, 6, 0, 0, 0)
        if kind == b'IDAT':
            compressed.extend(payload)
        offset += size + 12
    raw = zlib.decompress(compressed)
    assert len(raw) == 32 * 129
    result, previous = bytearray(), bytearray(128)
    for y in range(32):
        mode, row = raw[y*129], bytearray(raw[y*129+1:(y+1)*129])
        assert mode in range(5)
        for x in range(128):
            a, b, c = row[x-4] if x >= 4 else 0, previous[x], previous[x-4] if x >= 4 else 0
            p = a + b - c
            pa, pb, pc = abs(p-a), abs(p-b), abs(p-c)
            paeth = a if pa <= pb and pa <= pc else b if pb <= pc else c
            row[x] = (row[x] + [0, a, b, (a+b)//2, paeth][mode]) & 255
        result.extend(row)
        previous = row
    return result


def outputs():
    lines = ['// Generated by tools/generate_shell_icons.py; do not edit.',
             '// Tango icons: public domain. See romfs/shell/manifest.json.', '#pragma once',
             '#include <cstdint>', 'namespace ui { namespace shell_art {']
    manifest = {'upstream_commit': '41b8f6abd7ebb9d5c35e563c8cd8c410c88f114a',
                'license': 'Public Domain', 'notice': 'COPYING.tango', 'icons': []}
    for name, source in SOURCES:
        relative = f'icons/{name}.png'
        data = (ROOT / 'romfs/shell' / relative).read_bytes()
        rgba = decode(data)
        pixels = [(rgba[i+3] << 24) | (rgba[i] << 16) | (rgba[i+1] << 8) | rgba[i+2]
                  for i in range(0, len(rgba), 4)]
        lines.append(f'inline constexpr uint32_t {name}[1024] = {{')
        lines.extend('    ' + ','.join(f'0x{p:08x}u' for p in pixels[i:i+8]) + ','
                     for i in range(0, 1024, 8))
        lines.append('};')
        manifest['icons'].append({'file': relative, 'source': BASE+source,
                                  'sha256': hashlib.sha256(data).hexdigest(),
                                  'decoded_rgba_sha256': hashlib.sha256(rgba).hexdigest()})
    lines.append('} } // namespace ui::shell_art')
    header = '\n'.join(lines) + '\n'
    manifest['native_header'] = 'source/ui/shell_icons.h'
    manifest['native_header_sha256'] = hashlib.sha256(header.encode()).hexdigest()
    manifest['theme'] = 'Original native blue/green gradients and project mark; no Microsoft artwork.'
    manifest['fonts'] = '../fonts/ (Liberation; OFL.txt)'
    return {'source/ui/shell_icons.h': header, 'romfs/shell/manifest.json': json.dumps(manifest, indent=2)+'\n'}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for relative, content in outputs().items():
        path = ROOT / relative
        if args.check:
            assert path.read_text() == content, f'{relative}: regenerate with tools/generate_shell_icons.py'
        else:
            path.write_text(content)
    print('Shell artwork manifest/native pixels: PASS')


if __name__ == '__main__':
    main()
