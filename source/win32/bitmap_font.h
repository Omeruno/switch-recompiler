static constexpr size_t kFont5x7Count = sizeof(kFont5x7) / sizeof(kFont5x7[0]);

// Ищет глиф по кодпоинту (UTF-16 code unit — этого достаточно для всей
// кириллицы из BMP). nullptr, если символа нет (пропускаем его при
// отрисовке, не крашимся).
inline const FontGlyph* FindGlyph(uint32_t codepoint) {
    for (size_t i = 0; i < kFont5x7Count; i++) {
        if (kFont5x7[i].codepoint == codepoint) return &kFont5x7[i];
    }
    return nullptr;
}

// Рисует один глиф в ARGB-буфер шириной bufWidth, (x,y) — верхний левый угол.
// scale — целочисленный масштаб (1 = 5x8 пикселей как есть).
inline void DrawGlyph(uint32_t* pixels, int bufWidth, int bufHeight,
                       int x, int y, uint32_t codepoint, uint32_t color, int scale = 1) {
    const FontGlyph* g = FindGlyph(codepoint);
    if (!g) return;
    for (int row = 0; row < kFontRows; row++) {
        for (int col = 0; col < 5; col++) {
            if (g->rows[row][col] != '#') continue;
            for (int sy = 0; sy < scale; sy++) {
                for (int sx = 0; sx < scale; sx++) {
                    int px = x + col * scale + sx;
                    int py = y + row * scale + sy;
                    if (px < 0 || px >= bufWidth || py < 0 || py >= bufHeight) continue;
                    pixels[static_cast<size_t>(py) * bufWidth + px] = color;
                }
            }
        }
    }
}

// Рисует строку UTF-16 (len задаёт длину явно). Возвращает ширину в
// пикселях. '&' (маркер мнемоники в пунктах меню) не рисуется и не занимает
// места, как и в Windows (подчёркивание следующей буквы пока не делаем).
inline int DrawTextUtf16(uint32_t* pixels, int bufWidth, int bufHeight,
                          int x, int y, const uint16_t* text, size_t len,
                          uint32_t color, int scale = 1) {
    constexpr int kGlyphWidth = 5, kCharSpacing = 1;
    int cursorX = x;
    for (size_t i = 0; i < len; i++) {
        uint16_t ch = text[i];
        if (ch == '&') continue;
        if (ch == '\t') { cursorX += (kGlyphWidth + kCharSpacing) * scale * 4; continue; } // грубая табуляция
        DrawGlyph(pixels, bufWidth, bufHeight, cursorX, y, ch, color, scale);
        cursorX += (kGlyphWidth + kCharSpacing) * scale;
    }
    return cursorX - x;
}

// Как DrawTextUtf16, но для null-terminated строки
inline int DrawTextUtf16Z(uint32_t* pixels, int bufWidth, int bufHeight,
                           int x, int y, const uint16_t* text, uint32_t color, int scale = 1) {
    size_t len = 0;
    while (text[len] != 0) len++;
    return DrawTextUtf16(pixels, bufWidth, bufHeight, x, y, text, len, color, scale);
}

// Ширина текста в пикселях без отрисовки
inline int MeasureTextUtf16(const uint16_t* text, size_t len, int scale = 1) {
    constexpr int kGlyphWidth = 5, kCharSpacing = 1;
    int width = 0;
    for (size_t i = 0; i < len; i++) {
        if (text[i] == '&') continue;
        if (text[i] == '\t') { width += (kGlyphWidth + kCharSpacing) * scale * 4; continue; }
        width += (kGlyphWidth + kCharSpacing) * scale;
    }
    return width;
}

