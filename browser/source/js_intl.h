#define SWITCH_BROWSER_JS_INTL_H

// A bounded ru/en subset for the page reader. UTC is the only timezone.
static const char browser_intl[] =
"(() => {\n"
"const locale = input => {\n"
"  const value = String(Array.isArray(input) ? input[0] || 'ru' : input || 'ru').toLowerCase();\n"
"  return value === 'ru' || value.startsWith('ru-') ? 'ru' : 'en';\n"
"};\n"
"const finite = value => { value = Number(value); if (!Number.isFinite(value)) throw new RangeError('Non-finite value'); return value; };\n"
"const forms = {ru: {minute:['минуту','минуты','минут'],hour:['час','часа','часов'],day:['день','дня','дней']},en: {minute:['minute','minutes'],hour:['hour','hours'],day:['day','days']}};\n"
"class RelativeTimeFormat {\n"
"  constructor(input, options = {}) {\n"
"    this.lang = locale(input); this.numeric = options.numeric || 'always';\n"
"    if (!['always','auto'].includes(this.numeric) || (options.style && options.style !== 'long')) throw new RangeError('Unsupported relative format');\n"
"  }\n"
"  resolvedOptions() { return {locale:this.lang,numeric:this.numeric,style:'long',numberingSystem:'latn'}; }\n"
"  format(value, unit) {\n"
"    value = finite(value); unit = String(unit).replace(/s$/, '');\n"
"    const names = forms[this.lang][unit]; if (!names) throw new RangeError('Unsupported relative unit');\n"
"    if (this.numeric === 'auto') {\n"
"      if (unit === 'day' && [-1,0,1].includes(value)) return (this.lang === 'ru' ? ['вчера','сегодня','завтра'] : ['yesterday','today','tomorrow'])[value+1];\n"
"      if (value === 0) return this.lang === 'ru' ? (unit === 'minute' ? 'в эту минуту' : 'в этот час') : 'this ' + unit;\n"
"    }\n"
"    const amount = Math.abs(value), last = amount % 10, hundred = amount % 100;\n"
"    const index = this.lang === 'en' ? (amount === 1 ? 0 : 1) : (!Number.isInteger(amount) ? 1 : last === 1 && hundred !== 11 ? 0 : last >= 2 && last <= 4 && (hundred < 12 || hundred > 14) ? 1 : 2);\n"
"    const text = amount + ' ' + names[index];\n"
"    return value < 0 || Object.is(value, -0) ? text + (this.lang === 'ru' ? ' назад' : ' ago') : (this.lang === 'ru' ? 'через ' : 'in ') + text;\n"
"  }\n"
"}\n"
"const months = {ru:['янв.','февр.','мар.','апр.','мая','июн.','июл.','авг.','сент.','окт.','нояб.','дек.'],en:['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec']};\n"
"const weekdays = {ru:['вс','пн','вт','ср','чт','пт','сб'],en:['Sun','Mon','Tue','Wed','Thu','Fri','Sat']};\n"
"class DateTimeFormat {\n"
"  constructor(input, options = {}) {\n"
"    this.lang = locale(input); this.options = {...options};\n"
"    if ((options.timeZone && options.timeZone !== 'UTC') || options.hour12 === true || options.dateStyle || options.timeStyle || options.calendar && options.calendar !== 'gregory') throw new RangeError('Only Gregorian UTC 24-hour dates are supported');\n"
"    const allowed = {weekday:['short'],year:['numeric','2-digit'],month:['numeric','2-digit','short'],day:['numeric','2-digit'],hour:['numeric','2-digit'],minute:['numeric','2-digit'],second:['numeric','2-digit']};\n"
"    for (const key of Object.keys(allowed)) if (options[key] !== undefined && !allowed[key].includes(options[key])) throw new RangeError('Unsupported date option: ' + key);\n"
"    if (!Object.keys(allowed).some(key => options[key] !== undefined)) Object.assign(this.options,{year:'numeric',month:'numeric',day:'numeric'});\n"
"    this.format = this.format.bind(this);\n"
"  }\n"
"  resolvedOptions() { return {...this.options,locale:this.lang,timeZone:'UTC',calendar:'gregory',numberingSystem:'latn',hour12:false}; }\n"
"  format(value = Date.now()) {\n"
"    const date = new Date(finite(value)); if (Number.isNaN(date.getTime())) throw new RangeError('Invalid date');\n"
"    const o = this.options, result = [], time = [];\n"
"    const number = (value, style) => style === '2-digit' ? String(value).padStart(2,'0').slice(-2) : String(value);\n"
"    if (o.weekday) result.push(weekdays[this.lang][date.getUTCDay()]);\n"
"    if (o.day) result.push(number(date.getUTCDate(),o.day));\n"
"    if (o.month) result.push(o.month === 'short' ? months[this.lang][date.getUTCMonth()] : number(date.getUTCMonth()+1,o.month));\n"
"    if (o.year) result.push(number(date.getUTCFullYear(),o.year));\n"
"    if (o.hour) time.push(number(date.getUTCHours(),o.hour));\n"
"    if (o.minute) time.push(number(date.getUTCMinutes(),o.minute));\n"
"    if (o.second) time.push(number(date.getUTCSeconds(),o.second));\n"
"    if (time.length) result.push(time.join(':'));\n"
"    return result.join(' ');\n"
"  }\n"
"}\n"
"globalThis.Intl = {DateTimeFormat,RelativeTimeFormat};\n"
"})();\n";

#endif
